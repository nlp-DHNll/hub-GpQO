"""Prompt 模板。

所有 LLM 调用的 prompt 集中在此，方便调优和 A/B 测试。
每个模板都用 {占位符} 形式，调用方用 .format() 填充。
"""


# ============================================================
# 1. 规划阶段：把主题拆成子问题
# ============================================================

PLAN_PROMPT = """你的任务是把一个研究主题拆解成 {num_subquestions} 个子问题，覆盖该主题的不同维度，便于后续多角度检索。

主题：{topic}

要求：
- 每个子问题应该从不同角度切入（例如：背景/现状、关键事实/数据、争议/风险、未来趋势/对比）
- 子问题要具体、可检索，避免过于宽泛
- 严格输出 JSON 数组，每个元素包含 question（子问题字符串）和 rationale（为何重要，一句话）

输出示例：
[
  {{"question": "...", "rationale": "..."}},
  ...
]
"""


# ============================================================
# 2. 第 2 轮：分析信息缺口，生成补充 query
# ============================================================

GAP_PROMPT = """你正在进行一个多轮深度研究。当前已收集一轮信息，需要判断还有哪些信息缺口需要补检。

研究主题：{topic}

已检索的子问题：
{subquestions_text}

已收集到的内容（每条标注来源 URL）：
{summaries_text}

请输出 1~3 个补充检索 query（字符串数组），用于填补信息缺口。
如果信息已经足够全面，输出空数组 []。

输出格式：JSON 字符串数组。
"""


# ============================================================
# 3. 综合阶段：生成 5 节 Markdown 报告
# ============================================================

SYNTHESIS_PROMPT = """你是一位专业的中文研究员。基于以下检索到的资料，撰写一份关于 "{topic}" 的深度研究报告。

报告结构（严格遵守 5 节，使用二级 ## 标题，不要写 # 主标题）：
1. ## 摘要 —— 150~250 字，列出 3 条最关键发现
2. ## 背景 / 现状
3. ## 关键发现 —— 3~5 条，每条用 [n] 脚注引用来源编号
4. ## 风险 / 争议
5. ## 结论与遗留问题

写作要求：
- 从 ## 摘要 开始，不要写主标题（元信息会由系统附加）
- 在事实性陈述后用 [1][2] 这样的脚注引用来源编号
- 每个关键发现后用空格 + 括号标注置信度：🟢 高（≥2 独立来源）/ 🟡 中（1 个权威来源）/ 🔴 低（仅二手或来源不权威）/ ⚪ 模型推断（无来源）
- 文末不要写"来源列表"章节，会由系统自动附加

子问题（用于你理解主题覆盖维度）：
{subquestions_text}

资料（每条带编号、标题、URL、summary）：
{sources_text}

请直接输出 Markdown 报告正文，不要任何额外解释或前缀。"""
